"""
state.py - Formal definition of the shared graph state for the LangGraph
Plan & Execute Multi-Agent architecture with TruLens observability.

Inherits from MessagesState to maintain an evolving message history using
the `add_messages` reducer, enriched with attributes required for:
1. Initial planning and adaptive dynamic replanning (L2, L6).
2. Step-by-step dispatch and task instructions between planner_node and executor_node.
3. Bounded replanning attempt accounting per step (replan_attempts).
4. Persisting the final synthesized response or chart summary (final_answer).

It is also the single source of truth for cross-module primitives:
- load_environment(): idempotent `.env` loading (imported first by every module).
- HumanMessage / AIMessage / SystemMessage (with dependency-free fallbacks).
- DEFAULT_ENABLED_AGENTS and WORKER_AGENTS.
"""

import os
from typing import Any, Dict, List, Optional

# =====================================================================
# Environment Configuration (.env loading)
# =====================================================================

SKIP_DOTENV_ENV_VAR = "SALES_AGENT_SKIP_DOTENV"


def load_environment(dotenv_path: Optional[str] = None) -> bool:
    """
    Loads variables from a `.env` file into os.environ without overriding
    variables already exported in the shell (override=False).

    Set SALES_AGENT_SKIP_DOTENV=1 to disable loading (used by the test suite).
    Returns True when a `.env` file was found and loaded.
    """
    if os.getenv(SKIP_DOTENV_ENV_VAR) == "1":
        return False
    try:
        from dotenv import find_dotenv, load_dotenv
    except ImportError:
        return False
    path = dotenv_path or find_dotenv(usecwd=True)
    if not path:
        return False
    return bool(load_dotenv(path, override=False))


# Load `.env` before any tool or model reads its configuration.
load_environment()


# =====================================================================
# Message Classes (LangChain with dependency-free fallbacks)
# =====================================================================

try:
    from langchain_core.messages import AIMessage, HumanMessage, SystemMessage
except ImportError:
    class _FallbackMessage:
        type = "base"

        def __init__(self, content: str, name: Optional[str] = None):
            self.content = content
            self.name = name

        def __repr__(self):
            return f"{type(self).__name__}(content={self.content!r}, name={self.name!r})"

    class HumanMessage(_FallbackMessage):
        type = "human"

    class AIMessage(_FallbackMessage):
        type = "ai"

    class SystemMessage(_FallbackMessage):
        type = "system"


# =====================================================================
# Agent Registry
# =====================================================================

DEFAULT_ENABLED_AGENTS: List[str] = [
    "cortex_researcher",
    "web_researcher",
    "chart_generator",
    "chart_summarizer",
    "synthesizer",
]

# Worker nodes a plan step or an executor decision may target.
WORKER_AGENTS = frozenset(DEFAULT_ENABLED_AGENTS)

try:
    from pydantic import BaseModel, Field
except ImportError:
    class BaseModel:
        def __init__(self, **kwargs):
            for k, v in kwargs.items():
                setattr(self, k, v)
    def Field(default=None, **kwargs):
        return default

try:
    from langgraph.graph import MessagesState
except ImportError:
    from typing import TypedDict
    class MessagesState(TypedDict, total=False):
        messages: list


# =====================================================================
# Pydantic Models for Structured Output & Validation (LLM Outputs)
# =====================================================================

class PlanStep(BaseModel):
    """
    Represents an individual step within the plan generated by planner_node.
    Enriched with sub-goals, preconditions, and postconditions to support
    GPA (Goal-Plan-Act) alignment evaluations and inline evaluations with TruLens.
    """
    agent: str = Field(
        ...,
        description="Name of the assigned sub-agent (e.g., 'cortex_researcher', 'web_researcher', 'chart_generator', 'synthesizer')"
    )
    action: str = Field(
        ...,
        description="Detailed description of the specific action or operation the sub-agent must perform"
    )
    goal: Optional[str] = Field(
        default=None,
        description="Explicit verifiable sub-goal to achieve in this step (L6 GPA alignment)"
    )
    pre_conditions: Optional[List[str]] = Field(
        default_factory=list,
        description="Prerequisite data or conditions required before executing this step"
    )
    post_conditions: Optional[List[str]] = Field(
        default_factory=list,
        description="Expected verifiable outcomes or artifacts produced after completing this step"
    )


class ExecutorDecision(BaseModel):
    """
    Structured JSON schema emitted by executor_node after evaluating the state,
    active plan progress, and collected evidence.
    """
    replan: bool = Field(
        ...,
        description="True if collected evidence indicates the current plan must be revised by planner_node"
    )
    goto: str = Field(
        ...,
        description="Name of the next node to execute ('cortex_researcher', 'web_researcher', 'chart_generator', 'chart_summarizer', 'synthesizer', 'planner')"
    )
    reason: str = Field(
        ...,
        description="Detailed rationale explaining the executor's decision for traceability and auditability"
    )
    query: str = Field(
        ...,
        description="Specific actionable instruction ('agent_query') passed to the target agent for the current step"
    )


# =====================================================================
# LangGraph Shared State Schema
# =====================================================================

class State(MessagesState):
    """
    Global graph state for the LangGraph workflow.

    Inherits from MessagesState, which defines:
        messages: Annotated[list[AnyMessage], add_messages]
    tracking the multi-turn conversational history across agents.

    Extended Fields:
    ----------------
    user_query:
        Original user question or request triggering the workflow.
    enabled_agents:
        Modular list of enabled agent node names for the current session (allows
        dynamic capability toggling: web_researcher, cortex_researcher, chart_generator, etc.).
    plan:
        Dictionary indexed by step number as string or int (e.g., {"1": {...}, "2": {...}})
        containing planned steps, assigned agents, actions, sub-goals, and conditions.
    current_step:
        1-based index indicating the step currently being executed.
    agent_query:
        Actionable instruction ('inbox note') formulated by executor_node for the next agent.
    last_reason:
        Explanation of the most recent decision made by executor_node (provides continuity and traceability).
    replan_flag:
        Boolean flag. When True, signals that a revised plan was just created and the executor
        must execute the planned agent once before reconsidering.
    replan_attempts:
        Dictionary mapping {step_number: attempt_count} tracking replan attempts per step
        to enforce the MAX_REPLANS safety bound.
    final_answer:
        Final synthesized response string (prose report or chart caption) produced by
        'synthesizer' or 'chart_summarizer' before transitioning to END.
    chart_path:
        Validated relative path of the chart image produced by 'chart_generator' (or None).
    chart_notes:
        One-sentence insight emitted by 'chart_generator' alongside CHART_PATH (or None).
    language:
        Language code for user-facing text ('en' or 'es' for Latin American Spanish).
    """
    user_query: Optional[str]
    enabled_agents: Optional[List[str]]
    plan: Optional[Dict[str, Any]]
    current_step: int
    agent_query: Optional[str]
    last_reason: Optional[str]
    replan_flag: Optional[bool]
    replan_attempts: Optional[Dict[int, int]]
    final_answer: Optional[str]
    chart_path: Optional[str]
    chart_notes: Optional[str]
    language: Optional[str]
